// Alias for backwards compatibility
const CRUNCHY_ANIME_DATABASE = ANIME_PLUS_DATABASE;

// Helper database lookups
function getAnimeById(id) {
  return ANIME_PLUS_DATABASE.find(item => item.id === id) || ANIME_PLUS_DATABASE[0];
}

function getTop10Anime() {
  return ANIME_PLUS_DATABASE.filter(item => item.isTop10).sort((a, b) => a.rank - b.rank);
}

function getSimulcastAnime() {
  return ANIME_PLUS_DATABASE.filter(item => item.isSimulcast);
}

function getAnimeByGenre(genre) {
  if (!genre || genre.toLowerCase() === "all") return ANIME_PLUS_DATABASE;
  return ANIME_PLUS_DATABASE.filter(item => 
    item.genres.some(g => g.toLowerCase() === genre.toLowerCase())
  );
}

function getMovies() {
  return ANIME_PLUS_DATABASE.filter(item => 
    item.status === "Movie" || item.genres.some(g => g.toLowerCase() === "movie")
  );
}

function getLatestEpisodes() {
  const episodesList = [];
  ANIME_PLUS_DATABASE.forEach(anime => {
    if (anime.seasons && anime.seasons.length > 0) {
      anime.seasons.forEach(season => {
        if (season.episodes && season.episodes.length > 0) {
          season.episodes.forEach(ep => {
            const validBanner = (anime.banner && !anime.banner.toLowerCase().endsWith('.mp4')) ? anime.banner : anime.poster;
            const validThumb = (ep.thumbnail && !ep.thumbnail.toLowerCase().endsWith('.mp4')) ? ep.thumbnail : validBanner;
            episodesList.push({
              animeId: anime.id,
              animeTitle: anime.title,
              animePoster: anime.poster,
              animeBanner: validBanner,
              seasonTitle: season.seasonTitle,
              episodeId: ep.id,
              episodeNumber: ep.episodeNumber,
              title: ep.title,
              duration: ep.duration,
              thumbnail: validThumb,
              synopsis: ep.synopsis,
              videoUrl: ep.videoUrl
            });
          });
        }
      });
    }
  });
  return episodesList.slice(0, 10);
}
